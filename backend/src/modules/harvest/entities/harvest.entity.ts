import {
  Entity,
  Column,
  ManyToOne,
  JoinColumn,
  CreateDateColumn,
  UpdateDateColumn,
  PrimaryGeneratedColumn,
  type ValueTransformer,
} from 'typeorm';
import { User } from '@modules/users/entities/user.entity';
import { Tenant } from '@modules/tenants/entities/tenant.entity';
import { HarvestStatus } from '@/common/enums/harvest-status.enum';
import { HarvestQualityClass } from '@/common/enums/harvest-quality-class.enum';
import { ObjectType, Field, ID, Float, Int } from '@nestjs/graphql';
import { HarvestEntry } from './harvest-entry';

const dateTransformer: ValueTransformer = {
  to: (value: Date | string) =>
    typeof value === 'string' ? value : value?.toISOString?.().split('T')[0],
  from: (value: string | Date | null) =>
    value == null ? value : typeof value === 'string' ? new Date(value) : value,
};

// Backfill sub-entry fields added after rows were written so the non-null
// GraphQL fields never resolve to undefined for legacy entries:
//   - classC is new → default missing values to 0.
//   - brixClasses is new → default to a Quality A grade per existing Brix
//     reading, keeping the array index-aligned with brixReadings.
const entriesTransformer: ValueTransformer = {
  to: (value: HarvestEntry[] | undefined) => value,
  from: (value: HarvestEntry[] | null) =>
    value == null
      ? value
      : value.map((entry) => {
          const brixReadings = entry?.brixReadings ?? [];
          const brixClasses = entry?.brixClasses ?? [];
          return {
            ...entry,
            classC: entry?.classC ?? 0,
            brixClasses: brixReadings.map(
              (_, i) => brixClasses[i] ?? HarvestQualityClass.A,
            ),
          };
        }),
};

@ObjectType()
@Entity('harvests')
export class Harvest {
  @Field(() => ID)
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Field(() => ID)
  @Column({ type: 'uuid' })
  tenantId: string;

  @Field(() => ID, { nullable: true })
  @Column({ type: 'uuid', nullable: true })
  parentBatchId: string | null;

  @Field(() => Harvest, { nullable: true })
  @ManyToOne(() => Harvest, { onDelete: 'SET NULL' })
  @JoinColumn({ name: 'parentBatchId' })
  parentBatch?: Harvest | null;

  @Field(() => Tenant, { nullable: true })
  @ManyToOne(() => Tenant, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'tenantId' })
  tenant?: Tenant;

  @Field(() => ID, { nullable: true })
  @Column({ type: 'uuid', nullable: true })
  createdById: string | null;

  @Field(() => User, { nullable: true })
  @ManyToOne(() => User, { onDelete: 'SET NULL' })
  @JoinColumn({ name: 'createdById' })
  createdBy?: User | null;

  // --- Batch creation fields (dialog step) ---

  @Field()
  @Column({ type: 'varchar', length: 255 })
  species: string;

  @Field()
  @Column({ type: 'varchar', length: 255 })
  variety: string;

  @Field()
  @Column({ type: 'varchar', length: 255 })
  batch: string;

  // Human-readable identifier <varietyLetters>_<DDMMYYYY> (e.g. AK_08082001),
  // auto-generated by the service at creation from variety + plantingDate and
  // frozen afterwards. Nullable so the column can be added to existing rows;
  // historical rows are backfilled on module init. See VSL-198.
  @Field({ nullable: true })
  @Column({ type: 'varchar', length: 64, nullable: true })
  batchNumber?: string;

  @Field({ nullable: true })
  @Column({ type: 'varchar', length: 64, nullable: true })
  greenhouse?: string;

  @Field()
  @Column({ type: 'date', transformer: dateTransformer })
  plantingDate: Date;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  cultivationArea: number;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  numberOfRows: number;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  rowLength: number;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  plantsPerMeter: number;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  rowSpacing: number;

  @Field(() => Int)
  @Column({ type: 'int', default: 0 })
  totalPlants: number;

  @Field(() => Int)
  @Column({ type: 'int', default: 0 })
  lostPlants: number;

  @Field(() => HarvestStatus)
  @Column({
    type: 'enum',
    enum: HarvestStatus,
    default: HarvestStatus.ACTIVE,
  })
  status: HarvestStatus;

  // --- Sidebar harvest fields (log harvest step) ---

  @Field()
  @Column({ type: 'date', transformer: dateTransformer })
  date: Date;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  classA: number;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  classB: number;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  classC: number;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  waste: number;

  // Per-harvest sellable yield divided by the batch's plant count.
  // Auto-computed by the service on create/update from
  // `(classA + classB + classC) / totalPlants`. Null when the harvest has no
  // plant count (e.g. child harvest rows where totalPlants stays 0).
  @Field(() => Float, { nullable: true })
  @Column({ type: 'float', nullable: true })
  yieldPerPlant: number | null;

  // Per-harvest sellable yield divided by the row length in metres:
  // `(classA + classB + classC) / rowLength`. Auto-computed by the service on
  // create/update. Null when the harvest has no recorded row length
  // (rowLength <= 0).
  @Field(() => Float, { nullable: true })
  @Column({ type: 'float', nullable: true })
  yieldPerMeter: number | null;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  avgBrix: number;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  rowX: number;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  rowY: number;

  @Field(() => Float, {
    deprecationReason: 'Use rowX and rowY instead.',
  })
  get numberOfRowsHarvested(): number {
    if (this.rowX > 0 && this.rowY >= this.rowX) {
      return this.rowY - this.rowX + 1;
    }
    return 0;
  }

  // --- Brix measurements (dynamic list of readings) ---

  @Field(() => [Float])
  @Column({ type: 'jsonb', default: [] })
  brixReadings: number[];

  // Quality grade per Brix reading, index-aligned with brixReadings (pooled
  // across sub-entries on create/update). Empty for harvests logged before
  // grades were captured.
  @Field(() => [HarvestQualityClass])
  @Column({ type: 'jsonb', default: [] })
  brixClasses: HarvestQualityClass[];

  // --- Fruit weight measurement (fruit count + total weight → average) ---

  @Field(() => Int)
  @Column({ type: 'int', default: 0 })
  fruitCount: number;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  totalFruitWeight: number;

  @Field(() => Float)
  @Column({ type: 'float', default: 0 })
  avgFruitWeight: number;

  // --- Photos ---

  @Field(() => Int)
  @Column({ type: 'int', default: 0 })
  photos: number;

  @Field(() => [String], { nullable: true })
  @Column({ type: 'jsonb', nullable: true, default: [] })
  photoUrls?: string[];

  // --- Sub-entries ---

  // One "Log Harvest" submission may hold several sub-entries, each with its
  // own yield / brix / fruit-weight measurement. The top-level classA, classB,
  // waste, avgBrix, brixReadings, fruitCount, totalFruitWeight, avgFruitWeight,
  // rowX and rowY fields above are SUM/derived aggregates over these entries
  // (computed on create/update) so existing table, dashboard, CSV and
  // yieldPerPlant logic keeps reading the flat columns unchanged. Empty for
  // legacy rows logged before sub-entries existed.
  @Field(() => [HarvestEntry], { nullable: true })
  @Column({
    type: 'jsonb',
    nullable: true,
    default: [],
    transformer: entriesTransformer,
  })
  entries?: HarvestEntry[];

  // --- Timestamps ---

  @Field()
  @CreateDateColumn({ type: 'timestamp' })
  createdAt: Date;

  @Field()
  @UpdateDateColumn({ type: 'timestamp' })
  updatedAt: Date;
}
