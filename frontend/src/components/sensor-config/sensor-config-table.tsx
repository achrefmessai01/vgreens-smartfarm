'use client';

import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import {
  Sheet,
  SheetContent,
  SheetDescription,
  SheetHeader,
  SheetTitle,
} from '@/components/ui/sheet';
import { Switch } from '@/components/ui/switch';
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from '@/components/ui/table';
import { TableSkeleton } from '@/components/ui/table-skeleton';
import { useI18n } from '@/i18n';
import { SENSOR_CONFIG_FIELD_KEYS } from '@/lib/sensor-config-constants';
import { Pencil } from 'lucide-react';
import * as React from 'react';
import { SensorConfigForm } from './sensor-config-form';
import { useSensorConfig, type SensorRow } from './use-sensor-config';

interface SensorConfigTableProps {
  tenantId: string;
}

export function SensorConfigTable({ tenantId }: SensorConfigTableProps) {
  const { t } = useI18n();
  const sc = t.pages.admin.tenants.sensorConfig;

  const { rows, loading, saving, handleSave, handleDelete } =
    useSensorConfig(tenantId);
  const [editingRow, setEditingRow] = React.useState<SensorRow | null>(null);

  if (loading) {
    return <TableSkeleton columnCount={5} rowCount={6} showHeader />;
  }

  const columnLabels: Record<
    (typeof SENSOR_CONFIG_FIELD_KEYS)[number],
    string
  > = {
    xPosition: sc.xPosition,
    yPosition: sc.yPosition,
    greenhouse: sc.greenhouse,
  };

  return (
    <>
      <div className="border-border/60 overflow-hidden rounded-xl border shadow-sm">
        <Table>
          <TableHeader>
            <TableRow>
              <TableHead className="w-40">{sc.device}</TableHead>
              {SENSOR_CONFIG_FIELD_KEYS.map((key) => (
                <TableHead key={key}>{columnLabels[key]}</TableHead>
              ))}
              <TableHead className="w-24 text-center">
                {sc.visibleColumn}
              </TableHead>
              <TableHead className="text-right">{sc.actions}</TableHead>
            </TableRow>
          </TableHeader>
          <TableBody>
            {rows.length === 0 ? (
              <TableRow>
                <TableCell
                  colSpan={6}
                  className="text-muted-foreground py-10 text-center text-sm"
                >
                  {sc.noSensorsFound}
                </TableCell>
              </TableRow>
            ) : (
              rows.map((row) => {
                const { device, config, defaultPosition } = row;
                // Legacy seed rows often have xPosition === 0 AND yPosition === 0
                // — treat that combo as "no real override" and fall back to the
                // dynamic default so the table never shows zero/zero placeholders.
                const isLegacyZero =
                  config?.xPosition === 0 && config?.yPosition === 0;
                const hasXOverride = config?.xPosition != null && !isLegacyZero;
                const hasYOverride = config?.yPosition != null && !isLegacyZero;
                return (
                  <TableRow
                    key={device}
                    className="cursor-pointer"
                    onClick={() => setEditingRow(row)}
                  >
                    <TableCell className="font-medium">{device}</TableCell>
                    <TableCell>
                      {hasXOverride ? (
                        <Badge variant="secondary">{config!.xPosition}</Badge>
                      ) : defaultPosition ? (
                        <Badge
                          variant="outline"
                          className="text-muted-foreground border-dashed"
                          title={sc.autoGeneratedDefault}
                        >
                          {defaultPosition.xPosition}
                        </Badge>
                      ) : (
                        <span className="text-muted-foreground text-sm">-</span>
                      )}
                    </TableCell>
                    <TableCell>
                      {hasYOverride ? (
                        <Badge variant="secondary">{config!.yPosition}</Badge>
                      ) : defaultPosition ? (
                        <Badge
                          variant="outline"
                          className="text-muted-foreground border-dashed"
                          title={sc.autoGeneratedDefault}
                        >
                          {defaultPosition.yPosition}
                        </Badge>
                      ) : (
                        <span className="text-muted-foreground text-sm">-</span>
                      )}
                    </TableCell>
                    <TableCell>
                      {config?.greenhouse ? (
                        <Badge variant="secondary">{config.greenhouse}</Badge>
                      ) : (
                        <span className="text-muted-foreground text-sm">
                          {sc.notConfigured}
                        </span>
                      )}
                    </TableCell>
                    <TableCell
                      className="text-center"
                      onClick={(e) => e.stopPropagation()}
                    >
                      <Switch
                        checked={config?.hiddenInFarmOverview !== true}
                        disabled={saving}
                        aria-label={sc.showInFarmOverview}
                        onCheckedChange={(checked) => {
                          void handleSave({
                            device: row.device,
                            hiddenInFarmOverview: !checked,
                          });
                        }}
                      />
                    </TableCell>
                    <TableCell className="text-right">
                      <Button
                        variant="ghost"
                        size="icon"
                        className="h-8 w-8"
                        onClick={(e) => {
                          e.stopPropagation();
                          setEditingRow(row);
                        }}
                      >
                        <Pencil className="h-4 w-4" />
                      </Button>
                    </TableCell>
                  </TableRow>
                );
              })
            )}
          </TableBody>
        </Table>
      </div>

      <Sheet
        open={!!editingRow}
        onOpenChange={(open) => !open && setEditingRow(null)}
      >
        <SheetContent
          side="right"
          className="flex flex-col gap-0 p-0 sm:max-w-md"
        >
          <SheetHeader className="border-b px-6 pt-6 pb-4">
            <SheetTitle>{editingRow?.device}</SheetTitle>
            <SheetDescription>{sc.sheetDescription}</SheetDescription>
          </SheetHeader>
          {editingRow && (
            <div className="flex-1 overflow-y-auto px-6 py-5">
              <SensorConfigForm
                row={editingRow}
                tenantId={tenantId}
                onSave={handleSave}
                onDelete={handleDelete}
                saving={saving}
                onClose={() => setEditingRow(null)}
              />
            </div>
          )}
        </SheetContent>
      </Sheet>
    </>
  );
}
